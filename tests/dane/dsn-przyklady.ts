/** Postfix: opóźnienie (Action: delayed, 4.4.1) — miękkie, bez wykluczenia. */
export function postfixOpoznienie(msgid: string, odbiorca = "wolny@serwer-lezy.pl"): string {
  return postfixPelnaSkrzynka(msgid, odbiorca)
    .replace("Subject: Undelivered Mail Returned to Sender", "Subject: Delayed Mail (still being retried)")
    .replace("Action: failed", "Action: delayed")
    .replace("Status: 5.2.2", "Status: 4.4.1")
    .replace(/Diagnostic-Code: smtp; 552 5\.2\.2 .*$/m, "Diagnostic-Code: X-Postfix; connect to mx.serwer-lezy.pl[5.6.7.8]:25: Connection timed out")
    .replace("Will-Retry-Until", "Will-Retry-Until");
}

